"""Generated-C inventory and post-collection reporting; never imports the product.

The Cython adapter is deliberately version checked. Native validation reports
also check the policy and build/source snapshot recorded during collection.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET

import Cython
from Cython.Coverage import Plugin
from coverage import Coverage, CoverageData

from tools.coverage.support import environment_metadata, input_hashes, load_policy


PLUGIN_NAME = "Cython.Coverage.Plugin"


def discover_inventory(project_root, package, empty_sources=(), executable_sources=None):
    """Return absolute original-source paths and their traceable line sets.

    Empty sources must be declared explicitly: failed source discovery must not
    silently shrink the denominator. All generated C is read from this build.
    """
    root = Path(project_root).resolve()
    if Path.cwd().resolve() != root:
        raise ValueError("Discover sources from the measured project's own root")
    if Cython.__version__ != "3.3.0":
        raise ValueError("The inventory adapter requires Cython 3.3.0")
    package = (root / package).resolve()
    package.relative_to(root)
    sources = sorted(p for p in package.rglob("*") if p.suffix in (".pyx", ".pxi"))
    if any(not p.is_file() or p != p.resolve() or not p.is_relative_to(root) for p in sources):
        raise ValueError("Original sources must have unique canonical paths in this checkout")
    mains = [p for p in sources if p.suffix == ".pyx"]
    if not mains:
        raise ValueError(f"No Cython compilation sources in {package}")
    empty = {(root / p).resolve() for p in empty_sources}
    if not empty.issubset(sources):
        raise ValueError("Declared empty sources must exist in the source inventory")
    if executable_sources is not None:
        expected = {(root / p).resolve() for p in executable_sources}
        if set(sources) != empty | expected or empty & expected:
            raise ValueError("Source inventory changed; update the policy with an explained source-set change")
    generated = {p.with_suffix(".c") for p in mains}
    for c_file in generated:
        if not c_file.is_file():
            raise FileNotFoundError(f"Matching generated C is required: {c_file}")
        with c_file.open(encoding="utf8") as stream:
            if "Generated by Cython 3.3.0" not in stream.readline():
                raise ValueError(f"Unexpected Cython generator: {c_file}")

    plugin = Plugin()
    # Parse main modules first, so included files can find their containing C.
    for source in mains:
        reporter = plugin.file_reporter(str(source))
        if reporter is None or not reporter.lines():
            raise ValueError(f"No executable main-source mapping: {source}")
    # Version-sensitive access stays in this adapter. A traceable original not
    # in our enumerated input set must not disappear from the denominator.
    for source, (_, _, code) in plugin._c_files_map.items():
        if Path(source) == root / "(tree fragment)" and not Path(source).exists():
            # Cython's compiler-generated nodes have no original product file.
            continue
        if code and Path(source) not in sources:
            raise ValueError(f"Unexpected executable original-source mapping: {source}")
    inventory = {}
    for source in sources:
        reporter = plugin.file_reporter(str(source))
        lines = set(reporter.lines()) if reporter is not None else set()
        if reporter is not None and Path(reporter.c_file).resolve() not in generated:
            raise ValueError(f"Source mapped to a different build's C: {source}")
        if not lines and source not in empty:
            raise ValueError(f"Missing executable source mapping: {source}")
        if lines and source in empty:
            raise ValueError(f"Expected empty source has executable lines: {source}")
        inventory[str(source)] = lines
    return inventory


def measured_hits(data):
    return {name: sorted(data.lines(name) or []) for name in sorted(data.measured_files())}


def xml_accounting(xml_file, project_root):
    """Resolve XML source roots, rejecting ambiguous/out-of-project paths."""
    root = Path(project_root).resolve()
    xml = ET.parse(xml_file).getroot()
    bases = [root / (node.text or "") for node in xml.findall("./sources/source")]
    files = {}
    for node in xml.findall("./packages/package/classes/class"):
        filename = node.attrib["filename"]
        candidates = {(base / filename).resolve() for base in (bases or [root])}
        candidates = {p for p in candidates if p.is_file() and p.is_relative_to(root)}
        if len(candidates) != 1:
            raise ValueError(f"XML source does not resolve uniquely in project: {filename}")
        source = candidates.pop()
        name = source.relative_to(root).as_posix()
        if name in files or source.suffix not in (".py", ".pyx", ".pxi"):
            raise ValueError(f"Duplicate or unexpected product source: {name}")
        lines = node.findall("./lines/line")
        if any(int(line.attrib["hits"]) < 0 or int(line.attrib["number"]) < 1 for line in lines):
            raise ValueError(f"Invalid XML line accounting: {name}")
        hits = sorted(int(line.attrib["number"]) for line in lines if int(line.attrib["hits"]) > 0)
        misses = sorted(int(line.attrib["number"]) for line in lines if int(line.attrib["hits"]) == 0)
        if len(set(hits + misses)) != len(lines):
            raise ValueError(f"Duplicate executable line: {name}")
        files[name] = {"hits": hits, "misses": misses}
    lines = xml.findall(".//class/lines/line")
    if (int(xml.attrib["lines-valid"]) != len(lines)
            or int(xml.attrib["lines-covered"]) != sum(int(line.attrib["hits"]) > 0 for line in lines)):
        raise ValueError("XML aggregate counts disagree with source lines")
    return files


def seed_and_report(config_file, data_file, inventory, output, project_root, check=None):
    """Seed missing sources without changing hits, then generate validated XML."""
    root = Path(project_root).resolve()
    data_file = Path(data_file).resolve()
    output = Path(output).resolve()
    if not data_file.is_file():
        raise FileNotFoundError(f"Collected coverage data is required: {data_file}")
    package = Path(next(iter(inventory))).parent
    # Report from the verified directory, without importing the source package.
    cov = Coverage(config_file=str(config_file), data_file=str(data_file), source=[str(package)])
    cov.load()
    data = cov.get_data()
    if data.has_arcs():
        raise ValueError("Cython reporting requires line-mode coverage data")
    before = measured_hits(data)
    python_paths = list(package.rglob("*.py"))
    if any(p != p.resolve() or not p.is_relative_to(root) for p in python_paths):
        raise ValueError("Python sources must have unique canonical paths in this checkout")
    python_sources = {str(p) for p in python_paths}
    allowed = set(inventory) | python_sources
    for source in before:
        path = Path(source)
        if (not path.is_absolute() or str(path.resolve()) != source
                or not path.is_relative_to(root) or source not in allowed):
            raise ValueError(f"Unexpected or noncanonical measured product source: {source}")
        tracer = PLUGIN_NAME if source in inventory else ""
        if data.file_tracer(source) != tracer:
            raise ValueError(f"Unexpected compiled-source file tracer or Python association: {source}")
    nonempty = [source for source, lines in inventory.items() if lines]
    data.touch_files(nonempty, plugin_name=PLUGIN_NAME)
    # A report-only process doesn't run coverage's post-collector discovery.
    # Keep zero-hit Python modules too, using coverage.py's normal Python analysis.
    data.touch_files(sorted(python_sources))
    cov.save()
    after = measured_hits(data)
    if any(after[name] != lines for name, lines in before.items()):
        raise ValueError("Source seeding changed existing measured hits")
    temporary = output.with_name(output.name + ".tmp")
    try:
        cov.xml_report(outfile=str(temporary))
        files = xml_accounting(temporary, root)
        expected = {source: lines for source, lines in inventory.items() if lines}
        for source in sorted(python_sources):
            _, statements, _, _, _ = cov.analysis2(source)
            expected[source] = set(statements)
        expected_names = {str(Path(p).relative_to(root)) for p in expected}
        if set(files) != expected_names:
            raise ValueError(
                "XML product source set differs from Python discovery and compiled inventory: "
                f"unexpected={sorted(set(files) - expected_names)}, missing={sorted(expected_names - set(files))}"
            )
        for source, executable in expected.items():
            name = Path(source).relative_to(root).as_posix()
            reported = files.get(name)
            if reported is None or set(reported["hits"] + reported["misses"]) != executable:
                raise ValueError(f"XML executable inventory mismatch: {name}")
            if set(reported["hits"]) != set(data.lines(source) or []) & executable:
                raise ValueError(f"XML hit accounting mismatch: {name}")
        result = {
            "inventory": {str(Path(p).relative_to(root)): sorted(lines) for p, lines in inventory.items()},
            "empty_inventories": {
                str(Path(p).relative_to(root)): "declared compile-time/declaration-only input; no traceable lines"
                for p, lines in inventory.items() if not lines
            },
            "inventory_scope": "original product sources; excludes Cython-generated (tree fragment) nodes with no original file",
            "measured_before": {str(Path(p).relative_to(root)): lines for p, lines in before.items()},
            "measured_after": {str(Path(p).relative_to(root)): lines for p, lines in after.items()},
            "files": files,
            "totals": totals(files.values()),
            "accounting": {
                kind: totals(f for p, f in files.items() if (Path(p).suffix == ".py") == (kind == "python"))
                for kind in ("python", "compiled")
            },
        }
        if check:
            check(result)
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)
    return result


def totals(files):
    files = list(files)
    return {
        "executable": sum(len(f["hits"]) + len(f["misses"]) for f in files),
        "covered": sum(len(f["hits"]) for f in files),
        "missed": sum(len(f["misses"]) for f in files),
    }


def validate_collection(root, policy_file, config_file, data_file, metadata_file, replay=False):
    policy = load_policy(policy_file)
    record = json.loads(Path(metadata_file).read_text(encoding="utf8"))
    if (not replay and record["project_root"] != str(root)) or record["policy"] != policy:
        raise ValueError("Collection used a different checkout or coverage policy")
    if record["pytest_exit"] != 0:
        raise ValueError("Successful pytest collection/execution is required before final reporting")
    if not replay and record["data_file"] != str(Path(data_file).resolve()):
        raise ValueError("Coverage data does not match the recorded collection path")
    if record["versions"] != environment_metadata()["versions"]:
        raise ValueError("Build/collection and reporting tool versions must match")
    current = input_hashes(root, policy["package"], config_file, policy_file, root / record["extension"])
    if current != record["input_hashes"]:
        raise ValueError("Build, source, configuration, or policy changed after collection")
    return policy, record


def replay_data(record, source, destination, root):
    """Relocate only recorded canonical checkout paths, preserving tracer data."""
    if not Path(source).is_file():
        raise FileNotFoundError("Collected artifact coverage data is required")
    original_root = Path(record["project_root"])
    original = CoverageData(basename=str(source))
    original.read()

    def relocate(name):
        path = Path(name)
        if not path.is_absolute() or str(path) != name or ".." in path.parts:
            raise ValueError(f"Noncanonical artifact data path: {name}")
        relative = path.relative_to(original_root).as_posix()
        if relative not in record["input_hashes"]:
            raise ValueError(f"Unrecorded artifact data source: {name}")
        return str(root / relative)

    for name in original.measured_files():
        relocate(name)
    data = CoverageData(basename=str(destination))
    data.erase()
    data.update(original, map_path=relocate)
    data.write()


def native_anchors(root, files, selection):
    """Check known body statements reached by the existing native tests."""
    anchors = [
        ("pyobjus/pyobjus_types.pxi", "    return NSArray().arrayWithObjects_(*args)", "hits"),
        ("pyobjus/pyobjus_types.pxi", "    return NSDictionary().dictionaryWithObjects_forKeys_(pyobjus_values, pyobjus_keys)", "hits"),
        ("pyobjus/pyobjus_conversions.pxi", "    if py_ptr is None:", "misses" if selection == "literals" else "hits"),
    ]
    if selection == "full":
        anchors.append(("pyobjus/type_enc.pxi", "    type_enc_list = []", "hits"))
    results = []
    for source, text, expected in anchors:
        lines = (root / source).read_text(encoding="utf8").splitlines()
        matches = [number for number, line in enumerate(lines, 1) if line == text]
        if len(matches) != 1 or matches[0] not in files.get(source, {}).get(expected, []):
            raise ValueError(f"Native {expected} anchor failed: {source}: {text.strip()}")
        results.append({"source": source, "line": matches[0], "expected": expected, "statement": text.strip()})
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", help="Explicit package for standalone fixture reporting")
    parser.add_argument("--config")
    parser.add_argument("--data-file", default=".coverage")
    parser.add_argument("--empty-source", action="append", default=[])
    parser.add_argument("--policy")
    parser.add_argument("--metadata", default="build/coverage-run.json")
    parser.add_argument("--native-checks", choices=("full", "literals"), default="full")
    parser.add_argument("--artifacts", type=Path)
    parser.add_argument("--output", default="coverage.xml", type=Path)
    parser.add_argument("--check-fresh", action="store_true", help="Require identical previous source accounting")
    parser.add_argument("--from-artifacts", type=Path, help="Re-report a retained bundle without importing/rebuilding its extension")
    args = parser.parse_args()
    args.output = args.output.resolve()
    args.artifacts = args.artifacts.resolve() if args.artifacts else None
    previous = None
    if args.from_artifacts:
        bundle = args.from_artifacts.resolve()
        if args.artifacts or args.package or args.policy or args.config or args.empty_source:
            parser.error("Artifact replay uses only the bundle's recorded inputs")
        args.metadata = bundle / "collection.json"
        previous = json.loads((bundle / "manifest.json").read_text(encoding="utf8"))
        record = json.loads(args.metadata.read_text(encoding="utf8"))
        root = bundle / "sources"
        args.policy, args.config = root / record["policy_file"], root / record["config_file"]
        args.data_file = args.output.with_suffix(".data")
        os.chdir(root)
        # Verify input provenance before transforming coverage data paths.
        validate_collection(root, args.policy, args.config, args.data_file, args.metadata, replay=True)
        replay_data(record, bundle / "coverage-data.sqlite", args.data_file, root)
    root = Path.cwd().resolve()
    record = None
    if args.package is None or args.policy is not None:
        policy_file = Path(args.policy or "tools/coverage/policy.json").resolve()
        config = Path(args.config or "tools/coverage/coverage.toml").resolve()
        policy, record = validate_collection(root, policy_file, config, args.data_file, args.metadata, replay=bool(args.from_artifacts))
        package = policy["package"]
        if args.package not in (None, package) or args.empty_source:
            parser.error("Policy reporting uses its recorded package and empty-source declarations")
        empty_sources = policy["empty_sources"]
    else:
        package, empty_sources = args.package, args.empty_source
        config = Path(args.config or "coverage.ini").resolve()
    inventory = discover_inventory(root, package, empty_sources, policy["executable_sources"] if record else None)
    if args.check_fresh:
        previous = json.loads(args.output.with_suffix(".json").read_text(encoding="utf8"))
    if args.artifacts and record is None:
        parser.error("Artifact bundles require collection metadata and a policy")

    def validate_result(result):
        if record is not None:
            result["collection"] = record
            if package == "pyobjus":
                selection = ["tests/test_literals.py", "-v"] if args.native_checks == "literals" else ["tests", "-v"]
                if record["pytest_args"] != selection:
                    raise ValueError("Native body checks require the matching full-suite or isolated literals-only selection")
                result["native_anchors"] = native_anchors(root, result["files"], args.native_checks)
        if previous is not None and any(result[key] != previous[key] for key in ("files", "inventory", "totals", "accounting")):
            raise ValueError("Fresh reporting changed source accounting")

    result = seed_and_report(config, args.data_file, inventory, args.output, root, check=validate_result)
    args.output.with_suffix(".json").write_text(json.dumps(result, indent=2) + "\n")
    if args.artifacts:
        args.artifacts.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(args.data_file, args.artifacts / "coverage-data.sqlite")
        shutil.copyfile(args.output, args.artifacts / "coverage.xml")
        shutil.copyfile(args.metadata, args.artifacts / "collection.json")
        (args.artifacts / "manifest.json").write_text(json.dumps(result, indent=2) + "\n")
        for name in record["input_hashes"]:
            destination = args.artifacts / "sources" / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(root / name, destination)
    print(json.dumps(result["totals"], indent=2))


if __name__ == "__main__":
    main()
