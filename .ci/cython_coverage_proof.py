"""Prove post-bootstrap Cython line coverage on macOS/Python 3.14.

Initialization is excluded from hits; its traceable lines remain in the
denominator. Collect and report in separate processes from the checkout root,
keeping the matching generated C, original sources, and extension available.
"""

import argparse
import hashlib
import importlib
from importlib import metadata
from importlib.machinery import EXTENSION_SUFFIXES
import json
import os
from pathlib import Path
import platform
import sys
import xml.etree.ElementTree as ET

from Cython.Coverage import Plugin
from coverage import Coverage


PINS = {"Cython": "3.3.0", "coverage": "7.17.0", "pytest": "9.1.1"}
PLUGIN = "Cython.Coverage.Plugin"


def collector(package, output):
    cov = Coverage(config_file=False, source=[str(Path(package).resolve())],
                   data_file=str(output / "coverage.data"))
    cov.set_option("run:core", "ctrace")
    cov.set_option("run:plugins", ["Cython.Coverage"])
    return cov


def inventory(package, empty_sources):
    """Use the pinned Cython reporter, distinguishing empty includes from errors."""
    if metadata.version("Cython") != PINS["Cython"]:
        raise ValueError("Source discovery requires the pinned Cython version")
    sources = sorted(p.resolve() for p in Path(package).iterdir() if p.suffix in (".pyx", ".pxi"))
    mains = [p for p in sources if p.suffix == ".pyx"]
    if not mains or not set(empty_sources).issubset(p.name for p in sources):
        raise ValueError("Missing Cython compilation sources or declared empty includes")
    generated = {p.with_suffix(".c") for p in mains}
    for c_file in generated:
        with c_file.open(encoding="utf8") as stream:
            if f"Generated by Cython {PINS['Cython']}" not in stream.readline():
                raise ValueError(f"Mismatched Cython generator: {c_file}")
    plugin = Plugin()
    result = {}
    # Main modules prime the plugin's containing-C maps before include discovery.
    for source in mains + [p for p in sources if p not in mains]:
        reporter = plugin.file_reporter(str(source))
        lines = set(reporter.lines()) if reporter is not None else set()
        if bool(lines) == (source.name in empty_sources):
            raise ValueError(f"Unexpected executable/empty source inventory: {source}")
        if reporter is not None and Path(reporter.c_file).resolve() not in generated:
            raise ValueError(f"Source mapped to another build: {source}")
        result[str(source)] = lines
    return result


def fingerprints(package, binaries):
    paths = {p.resolve() for p in Path(package).rglob("*")
             if p.is_file() and p.suffix in (".py", ".pyx", ".pxi", ".h", ".c")}
    paths.update(Path(p) for p in binaries)
    paths.update(Path(p).resolve() for p in (
        "setup.py", "pyproject.toml", ".ci/cython_coverage_proof.py", ".ci/coverage-requirements.txt",
    ) if Path(p).is_file())
    return {str(p.relative_to(Path.cwd())): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths)}


def collect(package, tests, output):
    import pytest

    if any(name == package or name.startswith(package + ".") for name in sys.modules):
        raise ValueError("Product was imported before the bootstrap boundary")
    output.mkdir(parents=True, exist_ok=False)
    sys.path.insert(0, str(Path.cwd()))
    importlib.import_module(package)  # Deliberately outside the measurement interval.
    binaries = [str(Path(module.__file__).resolve()) for name, module in list(sys.modules.items())
                if name.startswith(package + ".")
                and str(getattr(module, "__file__", "")).endswith(tuple(EXTENSION_SUFFIXES))]
    if not binaries or any(not Path(p).is_relative_to(Path(package).resolve()) for p in binaries):
        raise ValueError("Bootstrap must load the compiled extension from this checkout")
    record = {
        "scope": "post-bootstrap execution over the full traceable-source inventory",
        "root": str(Path.cwd()), "package": package, "tests": tests,
        "python": sys.version, "platform": platform.platform(), "architecture": platform.machine(),
        "versions": {name: metadata.version(name) for name in (*PINS, "setuptools", "wheel")},
        "binaries": binaries, "inputs": fingerprints(package, binaries), "pytest_exit": None,
    }
    cov = collector(package, output)
    cov.start()
    try:
        status = pytest.main(["-p", "no:pytest_cov", *tests])
        record["pytest_exit"] = int(status)
    finally:
        cov.stop()
        cov.save()
        (output / "collection.json").write_text(json.dumps(record, indent=2) + "\n")
    return int(status)


def xml_files(path):
    xml = ET.parse(path).getroot()
    roots = [Path(node.text or ".") for node in xml.findall("./sources/source")]
    files = {}
    for node in xml.findall("./packages/package/classes/class"):
        candidates = {(base / node.attrib["filename"]).resolve() for base in roots}
        candidates = {p for p in candidates if p.is_file() and p.is_relative_to(Path.cwd())}
        if len(candidates) != 1:
            raise ValueError(f"Unresolvable/ambiguous XML source: {node.attrib['filename']}")
        source = candidates.pop()
        name = str(source.relative_to(Path.cwd()))
        if name in files or source.suffix not in (".py", ".pyx", ".pxi"):
            raise ValueError(f"Duplicate or unexpected report source: {name}")
        lines = node.findall("./lines/line")
        files[name] = {
            "hits": sorted(int(line.attrib["number"]) for line in lines if int(line.attrib["hits"]) > 0),
            "misses": sorted(int(line.attrib["number"]) for line in lines if int(line.attrib["hits"]) == 0),
        }
        if len(set(files[name]["hits"] + files[name]["misses"])) != len(lines):
            raise ValueError(f"Duplicate executable lines: {name}")
    return files


def native_checks(files, record):
    if record["tests"] not in (["tests", "-v"], ["tests/test_literals.py", "-v"]):
        raise ValueError("Native proof requires the full suite or isolated literals selection")
    full = record["tests"] == ["tests", "-v"]
    checks = [
        ("pyobjus/pyobjus_types.pxi", "    return NSArray().arrayWithObjects_(*args)", "hits"),
        ("pyobjus/pyobjus_types.pxi", "    return NSDictionary().dictionaryWithObjects_forKeys_(pyobjus_values, pyobjus_keys)", "hits"),
        ("pyobjus/pyobjus_conversions.pxi", "    if py_ptr is None:", "hits" if full else "misses"),
    ]
    if full:
        checks.append(("pyobjus/type_enc.pxi", "    type_enc_list = []", "hits"))
    for source, statement, expected in checks:
        matches = [i for i, text in enumerate(Path(source).read_text().splitlines(), 1) if text == statement]
        if len(matches) != 1 or matches[0] not in files.get(source, {}).get(expected, []):
            raise ValueError(f"Native {expected} check failed: {source}: {statement.strip()}")


def report(output, empty_sources, check=None, fresh=False):
    record = json.loads((output / "collection.json").read_text())
    if record["pytest_exit"] != 0 or record["root"] != str(Path.cwd()) or record["python"] != sys.version:
        raise ValueError("Reporting requires a successful collection in this checkout/interpreter")
    if any(metadata.version(name) != version for name, version in record["versions"].items()):
        raise ValueError("Collection/reporting versions changed")
    if record["inputs"] != fingerprints(record["package"], record["binaries"]):
        raise ValueError("Sources, generated C, binary, or build inputs changed after collection")
    sources = inventory(record["package"], empty_sources)
    if not (output / "coverage.data").is_file():
        raise FileNotFoundError("Collected coverage data is required")
    cov = collector(record["package"], output)
    cov.load()
    data = cov.get_data()
    if data.has_arcs():
        raise ValueError("Cython proof requires line coverage")
    before = {p: data.lines(p) for p in data.measured_files()}
    executable = [p for p, lines in sources.items() if lines]
    if any(p in before and data.file_tracer(p) != PLUGIN for p in executable):
        raise ValueError("Unexpected compiled-source file tracer")
    data.touch_files(executable, plugin_name=PLUGIN)
    cov.save()
    if any(set(data.lines(p) or []) != set(lines or []) for p, lines in before.items()):
        raise ValueError("Seeding changed existing hits")
    temporary = output / "coverage.xml.tmp"
    try:
        cov.xml_report(outfile=str(temporary))
        files = xml_files(temporary)
        for source, lines in sources.items():
            name = str(Path(source).relative_to(Path.cwd()))
            actual = files.get(name, {"hits": [], "misses": []})
            if set(actual["hits"] + actual["misses"]) != lines:
                raise ValueError(f"Incomplete executable inventory: {name}")
            if set(actual["hits"]) != lines & set(data.lines(source) or []):
                raise ValueError(f"Incorrect hit accounting: {name}")
        if check:
            check(files, record)
        result = {
            "collection": record, "files": files,
            "inventory": {str(Path(p).relative_to(Path.cwd())): sorted(lines) for p, lines in sources.items()},
            "totals": {key: sum(len(f[key]) for f in files.values()) for key in ("hits", "misses")},
        }
        summary = output / "report.json"
        if fresh and result != json.loads(summary.read_text()):
            raise ValueError("Fresh reporting changed source accounting")
        temporary.replace(output / "coverage.xml")
        summary.write_text(json.dumps(result, indent=2) + "\n")
        return result
    finally:
        temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("collect", "report"))
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--literals", action="store_true")
    parser.add_argument("--check-fresh", action="store_true")
    args = parser.parse_args()
    if sys.platform != "darwin" or sys.version_info[:2] != (3, 14):
        parser.error("Native proof requires macOS and Python 3.14")
    if {name: metadata.version(name) for name in PINS} != PINS:
        parser.error("Install .ci/coverage-requirements.txt for the controlled tracing stack")
    if os.environ.get("COVERAGE_CORE", "ctrace") != "ctrace" or os.environ.get("COVERAGE_PROCESS_START"):
        parser.error("Remove automatic/overridden coverage collection from the environment")
    if args.mode == "collect":
        if args.check_fresh:
            parser.error("--check-fresh is a reporting check")
        tests = ["tests/test_literals.py", "-v"] if args.literals else ["tests", "-v"]
        raise SystemExit(collect("pyobjus", tests, args.output))
    if args.literals:
        parser.error("--literals selects the collection, not the report")
    result = report(args.output, {"common.pxi", "config.pxi"}, native_checks, args.check_fresh)
    print(json.dumps(result["totals"], indent=2))


if __name__ == "__main__":
    main()
